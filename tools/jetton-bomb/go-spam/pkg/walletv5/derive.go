package walletv5

import (
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/binary"

	"github.com/xssnick/tonutils-go/address"
)

// TaggedSHA256 mirrors bench::tagged_sha256 in ton/benchmark/common.cpp:
// SHA256(seed || tag || u64le(index)). It is the deterministic keying primitive shared by the offline
// state generator and this spammer, so both derive identical wallet keys and fat addresses.
func TaggedSHA256(seed [32]byte, tag string, index uint64) [32]byte {
	h := sha256.New()
	h.Write(seed[:])
	h.Write([]byte(tag))
	var idx [8]byte
	binary.LittleEndian.PutUint64(idx[:], index)
	h.Write(idx[:])
	var out [32]byte
	copy(out[:], h.Sum(nil))
	return out
}

// DeriveW5 reconstructs the wallet-v5 #index generated by bench-state-gen: ed25519 seed =
// SHA256(seed || "w5" || u64le(index)), with the given raw wallet_id (state-gen's --wallet-id, default 0).
func DeriveW5(seed [32]byte, index uint64, walletID int32) *Wallet {
	keySeed := TaggedSHA256(seed, "w5", index)
	priv := ed25519.NewKeyFromSeed(keySeed[:])
	pub := priv.Public().(ed25519.PublicKey)
	return NewWithWalletID(pub, priv, walletID)
}

// FatAddress reconstructs the raw address of fat load-target #index in the basechain (workchain 0):
// address = SHA256(seed || "fat" || u64le(index)). Matches AccountType::Fat in state-gen.cpp, which
// places the account directly at this raw address in the zerostate (no state_init hash needed there).
func FatAddress(seed [32]byte, index uint64) *address.Address {
	h := TaggedSHA256(seed, "fat", index)
	return address.NewAddress(0, 0, h[:])
}
